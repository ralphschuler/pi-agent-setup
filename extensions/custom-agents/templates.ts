export function templateNames() {
  return customAgentTemplates.map((template) => template.templateName);
}

export function findTemplate(name: string) {
  const normalized = name.trim().toLowerCase();
  return customAgentTemplates.find((template) => template.templateName === normalized || template.name === normalized);
}

export function formatTemplateCatalog() {
  return customAgentTemplates.map((template) => `- ${template.templateName} — ${template.summary}`).join("\n");
}
